#!/usr/bin/env node
// tools/gen-manifest.js
// 扫描 engine/ 与 tools/ 目录，把 script 标签直接写入 index.html 的标记区块。
// 用法：node tools/gen-manifest.js
// 效果：新增引擎文件后跑一次即可，index.html 自动更新，浏览器原生同步加载。
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');

function collect(dir) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  const walk = (d) => {
    const entries = fs.readdirSync(d, { withFileTypes: true });
    entries.sort((a, b) => a.name.localeCompare(b.name));
    for (const e of entries) {
      const full = path.join(d, e.name);
      if (e.isDirectory()) walk(full);
      else if (e.name.endsWith('.js')) {
        out.push(path.relative(root, full).split(path.sep).join('/'));
      }
    }
  };
  walk(dir);
  return out;
}

// 核心加载顺序
const coreOrder = [
  'engine/core/rand.js',
  'engine/core/easing.js',
  'engine/core/renderer.js',
  'engine/core/webgl-postfx.js',
  'engine/core/webgl-effects.js',
  'engine/core/video-decode.js',
  'engine/core/exporter.js',
  'engine/plugin.js',
  'engine/scenelet.js',
  'engine/core/layout.js',
  'engine/core/motion.js',
  'engine/core/expression.js',
  'engine/core/audio.js',
  'engine/core/typography.js',
  'engine/core/scene.js',
  'engine/core/transition.js',
  'engine/core/postfx.js',
  'engine/core/runtime.js',
];

const coreSet = new Set(coreOrder);
const allCore = collect(path.join(root, 'engine/core'));
const allPalettes = collect(path.join(root, 'engine/palettes'));
const allEffects = collect(path.join(root, 'engine/effects'));
const allComponents = collect(path.join(root, 'engine/components'));
const allTemplates = collect(path.join(root, 'engine/templates'));
const allTools = collect(path.join(root, 'tools')).filter(f =>
  f.endsWith('/lint.js') || f.endsWith('/gen-schema.js') || f.endsWith('/critique.js') || f.endsWith('/validate-browser.js')
);

const templatesOrdered = [
  ...allTemplates.filter(f => f.endsWith('templates/index.js')),
  ...allTemplates.filter(f => !f.endsWith('templates/index.js')),
];

const ordered = [
  ...coreOrder.filter(f => fs.existsSync(path.join(root, f))),
  ...allCore.filter(f => !coreSet.has(f)),
  ...allPalettes,
  ...allEffects,
  ...allComponents,
  ...templatesOrdered,
  ...allTools,
  ...['engine/recommend.js'],
];

const tags = ordered.map(f => '  <script src="' + f + '"></script>').join('\n');

const htmlPath = path.join(root, 'index.html');
let html = fs.readFileSync(htmlPath, 'utf8');

const START = '<!-- RF_SCRIPTS_START -->';
const END = '<!-- RF_SCRIPTS_END -->';

if (html.indexOf(START) < 0 || html.indexOf(END) < 0) {
  console.error('index.html 缺少标记 ' + START + ' / ' + END);
  process.exit(1);
}

const re = new RegExp(START + '[\\s\\S]*?' + END);
html = html.replace(re, START + '\n' + tags + '\n  ' + END);
fs.writeFileSync(htmlPath, html);

// 同时输出 manifest.js（供其他工具/调试读取）
const manifestLines = [
  '// AUTO-GENERATED by tools/gen-manifest.js.',
  'window.RF_MANIFEST = [',
];
ordered.forEach((f, i) => {
  manifestLines.push('  ' + JSON.stringify(f) + (i < ordered.length - 1 ? ',' : ''));
});
manifestLines.push('];');
manifestLines.push('');
fs.writeFileSync(path.join(root, 'manifest.js'), manifestLines.join('\n'));

console.log('已更新 index.html 与 manifest.js，共 ' + ordered.length + ' 个脚本');
